import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { getOrderBundleData, recordBundleExport } from "./store";
import type { Session } from "./types";

// Built-in PDF fonts support Latin-1. User text is reduced predictably instead of causing failed exports.
const printable = (text: string) => text.normalize("NFKD").replace(/[^\x20-\x7e\xa0-\xff]/g, "?");
export async function generateEvidenceBundle(session: Session, orderId: string): Promise<Uint8Array> {
  const data = await getOrderBundleData(session, orderId);
  const pdf = await PDFDocument.create();
  pdf.setTitle(`RTG evidence - ${printable(data.order.reference)}`);
  pdf.setAuthor("RTG local sandbox");
  pdf.setSubject("Sandbox evidence export; no provider submission");
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  let page = pdf.addPage([595.28, 841.89]);
  let y = 790;
  const line = (text: string, size = 10, strong = false) => {
    const clean = printable(text);
    const chosenFont = strong ? bold : font;
    const words = clean.split(/\s+/).flatMap(word => {
      const pieces: string[] = []; let part = "";
      for (const character of word) {
        if (chosenFont.widthOfTextAtSize(part + character, size) > 510 && part) { pieces.push(part); part = character; }
        else part += character;
      }
      if (part) pieces.push(part); return pieces;
    }); let current = "";
    const render = (value: string) => {
      if (y < 60) { page = pdf.addPage([595.28, 841.89]); y = 790; }
      page.drawText(value, { x: 42, y, size, font: strong ? bold : font, color: rgb(.12,.2,.19) }); y -= size + 7;
    };
    for (const word of words) {
      if (chosenFont.widthOfTextAtSize(`${current} ${word}`, size) > 510 && current) { render(current); current = word; }
      else current += (current ? " " : "") + word;
    }
    render(current);
  };
  line("RTG / READY TO GO", 13, true); y -= 8;
  line("Order evidence bundle", 25, true); y -= 10;
  line("SANDBOX EXPORT - NO LIVE PROVIDER CONNECTION", 10, true);
  line(`Restaurant: ${data.restaurant.name} / ${data.location.name}`);
  line(`Order: ${data.order.reference} | Provider: ${data.order.provider} | Status: ${data.order.status}`);
  line(`Internal ID: ${data.order.id}`);
  line(`Provider order ID: ${data.order.providerOrderId || "Not supplied (manual / fixture order)"}`);
  line(`Order recorded: ${data.order.placedAt} | Exported: ${new Date().toISOString()}`);
  line(`Generated by: ${session.name}`); y -= 10;
  line("Items", 14, true);
  for (const item of data.order.items) line(`${item.quantity} x ${item.name}`);
  if (data.order.notes) line(`Notes: ${data.order.notes}`);
  y -= 10; line("Evidence manifest", 14, true);
  if (!data.photos.length) line("No photographs were attached at export time.");
  for (const { evidence } of data.photos) {
    line(`${evidence.stage} | ${evidence.filename} | ${evidence.size} bytes`, 10, true);
    line(`Server received: ${evidence.createdAt} | By: ${evidence.capturedBy}`);
    if (evidence.deviceCapturedAt) line(`Device reported capture: ${evidence.deviceCapturedAt} (unverified device clock)`);
    line(`SHA-256: ${evidence.sha256}`, 8);
    if (evidence.note) line(`Note: ${evidence.note}`);
    if (evidence.sealId) line(`Seal ID: ${evidence.sealId}`);
    if (evidence.handoverNote) line(`Handover note: ${evidence.handoverNote}`);
  }
  y -= 10; line("Audit trail", 14, true);
  for (const event of data.audit) line(`${event.createdAt} | ${event.action} | ${event.actor} | ${event.detail}`, 8);
  y -= 10; line("Limitations", 14, true);
  line("Photographs record the visible packing or handoff state. They do not prove delivery to a customer, the contents of a sealed package, or the absence of later handling. Device capture times are reported by the device; server receipt times are recorded separately. SHA-256 verifies stored bytes against this manifest, not the truth of a scene. This sandbox export is not submitted to any provider.", 9);
  for (const { evidence, bytes } of data.photos) {
    const image = evidence.mimeType === "image/png" ? await pdf.embedPng(bytes) : await pdf.embedJpg(bytes);
    const photoPage = pdf.addPage([595.28, 841.89]);
    photoPage.drawText(printable(`${data.order.reference} / ${evidence.stage}`), { x: 42, y: 792, font: bold, size: 14 });
    photoPage.drawText(printable(`Server received ${evidence.createdAt}`), { x: 42, y: 770, font, size: 9 });
    const scaled = image.scaleToFit(510, 650);
    photoPage.drawImage(image, { x: (595.28-scaled.width)/2, y: 95 + (650-scaled.height)/2, width: scaled.width, height: scaled.height });
    photoPage.drawText(`SHA-256 ${evidence.sha256}`, { x: 42, y: 62, size: 7, font });
  }
  const pages = pdf.getPages();
  pages.forEach((p, i) => p.drawText(`RTG sandbox | ${i + 1} / ${pages.length}`, { x: 42, y: 28, font, size: 8, color: rgb(.4,.45,.44) }));
  const output = await pdf.save();
  await recordBundleExport(session, orderId);
  return output;
}
